static void GuidOrderDemo()
{
    var start = new DateTimeOffset(2026, 11, 7, 9, 0, 0, TimeSpan.Zero);
    Guid[] v7 = Enumerable.Range(0, 5).Select(i => Guid.CreateVersion7(start.AddMilliseconds(i))).ToArray();
    var efGenerator = new SequentialGuidValueGenerator();
    Guid[] ef = Enumerable.Range(0, 5).Select(_ => efGenerator.Next(null!)).ToArray();

    Print("Guid.CreateVersion7, creation order", v7);
    Print("sorted like SQL Server (SqlGuid)", v7.OrderBy(g => new SqlGuid(g)).ToArray(), v7);
    Print("EF Core SequentialGuidValueGenerator, creation order", ef);
    Print("sorted like SQL Server (SqlGuid)", ef.OrderBy(g => new SqlGuid(g)).ToArray(), ef);
    Console.WriteLine($"version nibble: v7={v7[0].Version}, ef={ef[0].Version}");
}

static void Print(string title, Guid[] values, Guid[]? creationOrder = null)
{
    Console.WriteLine(title);
    foreach (Guid g in values)
        Console.WriteLine(creationOrder is null ? $"  {g}" : $"  {g}  #{Array.IndexOf(creationOrder, g) + 1}");
}

// Loads 200,000 rows into each benchmark table (tables come from sql/cd04-benchmark.sql)
static async Task LoadBenchmarkAsync(string connectionString)
{
    const int rows = 200_000, batch = 1_000;
    var efGenerator = new SequentialGuidValueGenerator();
    await using var cn = new SqlConnection(connectionString);
    await cn.OpenAsync();

    foreach (string table in new[] { "OrdInt", "OrdNewSeq" })
    {
        // Key is generated by the server (IDENTITY / NEWSEQUENTIALID)
        for (int i = 0; i < rows; i += batch)
            await BulkAsync(cn, table, NewTable(withId: false, withPublicId: false), i, batch, _ => null, null);
    }

    var generators = new (string Table, Func<Guid> Next)[]
    {
        ("OrdGuidV4", Guid.NewGuid),
        ("OrdGuidV7", Guid.CreateVersion7),
        ("OrdGuidEf", () => efGenerator.Next(null!)),
    };
    foreach (var (table, next) in generators)
        for (int i = 0; i < rows; i += batch)
            await BulkAsync(cn, table, NewTable(withId: true, withPublicId: false), i, batch, _ => next(), null);

    for (int i = 0; i < rows; i += batch)
        await BulkAsync(cn, "OrdSplit", NewTable(withId: false, withPublicId: true), i, batch, null, _ => Guid.CreateVersion7());

    Console.WriteLine($"loaded {rows:N0} rows into 6 tables");
}

static DataTable NewTable(bool withId, bool withPublicId)
{
    var t = new DataTable();
    if (withId) t.Columns.Add("Id", typeof(Guid));
    if (withPublicId) t.Columns.Add("PublicId", typeof(Guid));
    t.Columns.Add("CreatedAt", typeof(DateTime));
    t.Columns.Add("TotalAmount", typeof(decimal));
    t.Columns.Add("Note", typeof(string));
    return t;
}

static async Task BulkAsync(SqlConnection cn, string table, DataTable t, int offset, int count,
    Func<int, Guid?>? id, Func<int, Guid>? publicId)
{
    var baseTime = new DateTime(2026, 11, 1, 0, 0, 0, DateTimeKind.Utc);
    for (int n = offset; n < offset + count; n++)
    {
        DataRow r = t.NewRow();
        if (id is not null && t.Columns.Contains("Id")) r["Id"] = id(n)!.Value;
        if (publicId is not null) r["PublicId"] = publicId(n);
        r["CreatedAt"] = baseTime.AddSeconds(n);
        r["TotalAmount"] = 100m + n % 5_000;
        r["Note"] = $"Institutional order {n}";
        t.Rows.Add(r);
    }
    using var bulk = new SqlBulkCopy(cn) { DestinationTableName = "dbo." + table, BatchSize = count };
    foreach (DataColumn c in t.Columns)
        bulk.ColumnMappings.Add(c.ColumnName, c.ColumnName);
    await bulk.WriteToServerAsync(t);
}

static async Task OrdersDemoAsync(string connectionString)
{
    // The demo drops and recreates its own database, never the main one
    var csb = new SqlConnectionStringBuilder(connectionString);
    csb.InitialCatalog += "_Cd04";
    var options = new DbContextOptionsBuilder<BookstoreContext>().UseSqlServer(csb.ConnectionString).Options;
    await using (var setup = new BookstoreContext(options))
    {
        await setup.Database.EnsureDeletedAsync();
        await setup.Database.EnsureCreatedAsync();
    }

    await using var db = new BookstoreContext(options);
    db.Orders.AddRange(
        new Order { InstitutionId = 1, TotalAmount = 4_200m },
        new Order { InstitutionId = 1, TotalAmount = 1_250.50m },
        new Order { InstitutionId = 2, TotalAmount = 15_000m });
    await db.SaveChangesAsync();

    foreach (Order o in await db.Orders.OrderBy(o => o.Id).ToListAsync())
        Console.WriteLine($"Id={o.Id} PublicId={o.PublicId} Institution={o.InstitutionId}");

    var audit = new AuditEntry { Action = "order-created" };
    db.AuditEntries.Add(audit);
    Console.WriteLine($"EF-generated Guid key before SaveChanges: {audit.Id} (version {audit.Id.Version})");
    await db.SaveChangesAsync();

    Order first = await db.Orders.OrderBy(o => o.Id).FirstAsync();
    try
    {
        db.Entry(first).Property(o => o.PublicId).CurrentValue = OrderPublicId.New();
        await db.SaveChangesAsync();
    }
    catch (InvalidOperationException ex)
    {
        Console.WriteLine(ex.Message);
        db.Entry(first).State = EntityState.Unchanged;
        db.ChangeTracker.Clear();
    }

    OrderPublicId third = (await db.Orders.AsNoTracking().OrderBy(o => o.Id).LastAsync()).PublicId;
    Console.WriteLine(OrderQueries.FindQuery(db, 1, third).ToQueryString());
    foreach (int institutionId in new[] { 1, 2 })
    {
        Order? found = await OrderQueries.FindAsync(db, institutionId, third);
        Console.WriteLine(found is null
            ? $"Institution {institutionId} -> 404 Not Found"
            : $"Institution {institutionId} -> 200 OK, total {found.TotalAmount:0.00}");
    }
}
