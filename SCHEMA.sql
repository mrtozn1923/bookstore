CREATE TABLE dbo.categories (
    category_id        INT IDENTITY(1,1) NOT NULL,
    name               NVARCHAR(100)     NOT NULL,
    parent_category_id INT               NULL,
    CONSTRAINT PK_categories PRIMARY KEY (category_id),
    CONSTRAINT UQ_categories_name UNIQUE (name),
    CONSTRAINT FK_categories_parent FOREIGN KEY (parent_category_id) REFERENCES dbo.categories (category_id)
);

CREATE TABLE dbo.authors (
    author_id  INT IDENTITY(1,1) NOT NULL,
    first_name NVARCHAR(100)     NOT NULL,
    last_name  NVARCHAR(100)     NOT NULL,
    birth_year SMALLINT          NULL,
    CONSTRAINT PK_authors PRIMARY KEY (author_id)
);

CREATE TABLE dbo.books (
    book_id        INT IDENTITY(1,1) NOT NULL,
    isbn           CHAR(13)          NOT NULL,
    title          NVARCHAR(200)     NOT NULL,
    subtitle       NVARCHAR(200)     NULL,
    category_id    INT               NULL,
    language_code  CHAR(2)           NOT NULL CONSTRAINT DF_books_language_code DEFAULT ('en'),
    published_year SMALLINT          NULL,
    page_count     SMALLINT          NULL,
    list_price     DECIMAL(10,2)     NOT NULL,
    listed_on      DATE              NOT NULL,
    is_active      BIT               NOT NULL CONSTRAINT DF_books_is_active DEFAULT (1),
    CONSTRAINT PK_books PRIMARY KEY (book_id),
    CONSTRAINT UQ_books_isbn UNIQUE (isbn),
    CONSTRAINT FK_books_categories FOREIGN KEY (category_id) REFERENCES dbo.categories (category_id),
    CONSTRAINT CK_books_list_price CHECK (list_price >= 0),
    CONSTRAINT CK_books_page_count CHECK (page_count > 0)
);

CREATE TABLE dbo.book_authors (
    book_id      INT     NOT NULL,
    author_id    INT     NOT NULL,
    author_order TINYINT NOT NULL CONSTRAINT DF_book_authors_author_order DEFAULT (1),
    CONSTRAINT PK_book_authors PRIMARY KEY (book_id, author_id),
    CONSTRAINT FK_book_authors_books FOREIGN KEY (book_id) REFERENCES dbo.books (book_id) ON DELETE CASCADE,
    CONSTRAINT FK_book_authors_authors FOREIGN KEY (author_id) REFERENCES dbo.authors (author_id)
);

CREATE TABLE dbo.customers (
    customer_id  INT IDENTITY(1,1) NOT NULL,
    first_name   NVARCHAR(100)     NOT NULL,
    last_name    NVARCHAR(100)     NOT NULL,
    email        VARCHAR(254)      NOT NULL,
    phone        VARCHAR(20)       NULL,
    city         NVARCHAR(100)     NULL,
    country_code CHAR(2)           NOT NULL,
    created_at   DATETIME2(0)      NOT NULL CONSTRAINT DF_customers_created_at DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_customers PRIMARY KEY (customer_id),
    CONSTRAINT UQ_customers_email UNIQUE (email)
);

CREATE TABLE dbo.orders (
    order_id    INT IDENTITY(1,1) NOT NULL,
    customer_id INT               NOT NULL,
    ordered_at  DATETIME2(0)      NOT NULL,
    status      VARCHAR(20)       NOT NULL CONSTRAINT DF_orders_status DEFAULT ('Pending'),
    shipped_at  DATETIME2(0)      NULL,
    CONSTRAINT PK_orders PRIMARY KEY (order_id),
    CONSTRAINT FK_orders_customers FOREIGN KEY (customer_id) REFERENCES dbo.customers (customer_id),
    CONSTRAINT CK_orders_status CHECK (status IN ('Pending', 'Paid', 'Shipped', 'Delivered', 'Cancelled')),
    CONSTRAINT CK_orders_shipped_at CHECK (shipped_at >= ordered_at)
);

CREATE TABLE dbo.order_items (
    order_item_id INT IDENTITY(1,1) NOT NULL,
    order_id      INT               NOT NULL,
    book_id       INT               NOT NULL,
    quantity      INT               NOT NULL,
    unit_price    DECIMAL(10,2)     NOT NULL,
    CONSTRAINT PK_order_items PRIMARY KEY (order_item_id),
    CONSTRAINT UQ_order_items_order_book UNIQUE (order_id, book_id),
    CONSTRAINT FK_order_items_orders FOREIGN KEY (order_id) REFERENCES dbo.orders (order_id) ON DELETE CASCADE,
    CONSTRAINT FK_order_items_books FOREIGN KEY (book_id) REFERENCES dbo.books (book_id),
    CONSTRAINT CK_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT CK_order_items_unit_price CHECK (unit_price >= 0)
);

CREATE TABLE dbo.reviews (
    review_id   INT IDENTITY(1,1) NOT NULL,
    book_id     INT               NOT NULL,
    customer_id INT               NOT NULL,
    rating      TINYINT           NOT NULL,
    body        NVARCHAR(1000)    NULL,
    reviewed_at DATETIME2(0)      NOT NULL,
    CONSTRAINT PK_reviews PRIMARY KEY (review_id),
    CONSTRAINT UQ_reviews_book_customer UNIQUE (book_id, customer_id),
    CONSTRAINT FK_reviews_books FOREIGN KEY (book_id) REFERENCES dbo.books (book_id),
    CONSTRAINT FK_reviews_customers FOREIGN KEY (customer_id) REFERENCES dbo.customers (customer_id),
    CONSTRAINT CK_reviews_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE TABLE dbo.stock_items (
    book_id          INT          NOT NULL,
    quantity_on_hand INT          NOT NULL,
    reorder_level    INT          NOT NULL CONSTRAINT DF_stock_items_reorder_level DEFAULT (5),
    updated_at       DATETIME2(0) NOT NULL CONSTRAINT DF_stock_items_updated_at DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT PK_stock_items PRIMARY KEY (book_id),
    CONSTRAINT FK_stock_items_books FOREIGN KEY (book_id) REFERENCES dbo.books (book_id),
    CONSTRAINT CK_stock_items_quantity_on_hand CHECK (quantity_on_hand >= 0)
);

CREATE TABLE dbo.payments (
    payment_id INT IDENTITY(1,1) NOT NULL,
    order_id   INT               NOT NULL,
    method     VARCHAR(20)       NOT NULL,
    amount     DECIMAL(10,2)     NOT NULL,
    paid_at    DATETIME2(0)      NOT NULL,
    CONSTRAINT PK_payments PRIMARY KEY (payment_id),
    CONSTRAINT FK_payments_orders FOREIGN KEY (order_id) REFERENCES dbo.orders (order_id),
    CONSTRAINT CK_payments_method CHECK (method IN ('card', 'bank_transfer', 'gift_card')),
    CONSTRAINT CK_payments_amount CHECK (amount > 0)
);


