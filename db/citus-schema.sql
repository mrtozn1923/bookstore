CREATE TABLE books (
    book_id  int PRIMARY KEY,
    isbn     char(13) NOT NULL UNIQUE,
    title    text NOT NULL,
    category text NOT NULL,
    price    numeric(10,2) NOT NULL
);
SELECT create_reference_table('books');

CREATE TABLE customers (
    customer_id int PRIMARY KEY,
    email       text NOT NULL,
    full_name   text NOT NULL,
    country     char(2) NOT NULL,
    created_at  timestamptz NOT NULL
);
SELECT create_distributed_table('customers', 'customer_id');

CREATE TABLE orders (
    order_id     bigint GENERATED BY DEFAULT AS IDENTITY,
    customer_id  int NOT NULL REFERENCES customers,
    status       text NOT NULL,
    total_amount numeric(12,2) NOT NULL,
    currency     char(3) NOT NULL DEFAULT 'TRY',
    created_at   timestamptz NOT NULL,
    PRIMARY KEY (customer_id, order_id)
);
SELECT create_distributed_table('orders', 'customer_id', colocate_with => 'customers');

CREATE TABLE order_items (
    customer_id int NOT NULL,
    order_id    bigint NOT NULL,
    line_no     smallint NOT NULL,
    book_id     int NOT NULL,
    quantity    int NOT NULL,
    unit_price  numeric(10,2) NOT NULL,
    PRIMARY KEY (customer_id, order_id, line_no)
);
SELECT create_distributed_table('order_items', 'customer_id', colocate_with => 'orders');
ALTER TABLE order_items ADD FOREIGN KEY (customer_id, order_id) REFERENCES orders;
ALTER TABLE order_items ADD FOREIGN KEY (book_id) REFERENCES books;

CREATE INDEX ix_orders_customer_created ON orders (customer_id, created_at DESC);
