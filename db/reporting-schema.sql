-- Reporting schema managed by the DBA team (not by EF Core migrations)
CREATE SCHEMA reporting;
GO

CREATE TABLE reporting.CATEGORY (
    CATEGORY_ID   int IDENTITY(1,1) NOT NULL CONSTRAINT PK_CATEGORY PRIMARY KEY,
    CATEGORY_NAME nvarchar(100) NOT NULL
);

CREATE TABLE reporting.BOOK_SALES (
    SALE_ID     bigint IDENTITY(1,1) NOT NULL CONSTRAINT PK_BOOK_SALES PRIMARY KEY,
    ISBN        char(13) NOT NULL,
    BOOK_TITLE  nvarchar(200) NOT NULL,
    CATEGORY_ID int NOT NULL CONSTRAINT FK_BOOK_SALES_CATEGORY REFERENCES reporting.CATEGORY (CATEGORY_ID),
    SOLD_AT     datetime2(0) NOT NULL CONSTRAINT DF_BOOK_SALES_SOLD_AT DEFAULT (SYSUTCDATETIME()),
    QUANTITY    int NOT NULL CONSTRAINT CK_BOOK_SALES_QUANTITY CHECK (QUANTITY > 0),
    UNIT_PRICE  decimal(10,2) NOT NULL,
    LINE_TOTAL  AS (QUANTITY * UNIT_PRICE) PERSISTED,
    ROW_VER     rowversion NOT NULL
);

CREATE INDEX IX_BOOK_SALES_SOLD_AT ON reporting.BOOK_SALES (SOLD_AT) INCLUDE (QUANTITY, UNIT_PRICE);

CREATE TABLE reporting.IMPORT_LOG (
    FILE_NAME   nvarchar(260) NOT NULL,
    IMPORTED_AT datetime2(0) NOT NULL,
    ROW_COUNT   int NOT NULL
);

CREATE TABLE dbo.ETL_STATE (
    JOB_NAME varchar(50) NOT NULL CONSTRAINT PK_ETL_STATE PRIMARY KEY,
    LAST_RUN datetime2(0) NULL
);
GO

CREATE VIEW reporting.vw_DAILY_SALES
AS
SELECT CAST(s.SOLD_AT AS date) AS SALE_DATE,
       c.CATEGORY_NAME,
       SUM(s.QUANTITY)   AS UNITS,
       SUM(s.LINE_TOTAL) AS REVENUE
FROM reporting.BOOK_SALES AS s
JOIN reporting.CATEGORY AS c ON c.CATEGORY_ID = s.CATEGORY_ID
GROUP BY CAST(s.SOLD_AT AS date), c.CATEGORY_NAME;
GO

