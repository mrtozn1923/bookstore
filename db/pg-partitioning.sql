CREATE SCHEMA IF NOT EXISTS archive;

CREATE TABLE orders_p (
    order_id     bigint GENERATED BY DEFAULT AS IDENTITY,
    customer_id  int NOT NULL,
    status       text NOT NULL,
    total_amount numeric(12,2) NOT NULL,
    currency     char(3) NOT NULL DEFAULT 'TRY',
    created_at   timestamptz NOT NULL,
    PRIMARY KEY (order_id, created_at)
) PARTITION BY RANGE (created_at);

CREATE TABLE order_items_p (
    order_id   bigint NOT NULL,
    line_no    smallint NOT NULL,
    created_at timestamptz NOT NULL,
    book_id    int NOT NULL REFERENCES books,
    quantity   int NOT NULL,
    unit_price numeric(10,2) NOT NULL,
    PRIMARY KEY (order_id, line_no, created_at),
    FOREIGN KEY (order_id, created_at) REFERENCES orders_p
) PARTITION BY RANGE (created_at);

CREATE INDEX ix_orders_p_customer_created ON orders_p (customer_id, created_at DESC);

CREATE FUNCTION create_month_partitions(p_from date, p_to date)
RETURNS int
LANGUAGE plpgsql AS $$
DECLARE
    m date;
    created int := 0;
BEGIN
    FOR m IN SELECT generate_series(date_trunc('month', p_from), p_to, interval '1 month')::date LOOP
        CONTINUE WHEN to_regclass('orders_' || to_char(m, 'YYYY_MM')) IS NOT NULL;
        EXECUTE format('CREATE TABLE %I PARTITION OF orders_p FOR VALUES FROM (%L) TO (%L)',
                       'orders_' || to_char(m, 'YYYY_MM'), m, (m + interval '1 month')::date);
        EXECUTE format('CREATE TABLE %I PARTITION OF order_items_p FOR VALUES FROM (%L) TO (%L)',
                       'order_items_' || to_char(m, 'YYYY_MM'), m, (m + interval '1 month')::date);
        created := created + 1;
    END LOOP;
    RETURN created;
END
$$;

SELECT create_month_partitions('2022-11-01', '2026-12-01');
